describe('highway_width_fallbacks', function()
  local highway_width_fallbacks = require('topics.helper.highway_width_fallbacks')

  describe('is_oneway_highway', function()
    it('is true for yes, implicit_yes, and car_not_bike', function()
      assert.is_true(highway_width_fallbacks.is_oneway_highway('yes'))
      assert.is_true(highway_width_fallbacks.is_oneway_highway('implicit_yes'))
      assert.is_true(highway_width_fallbacks.is_oneway_highway('car_not_bike'))
    end)

    it('is false for other values', function()
      assert.is_false(highway_width_fallbacks.is_oneway_highway('no'))
      assert.is_false(highway_width_fallbacks.is_oneway_highway(nil))
    end)
  end)

  describe('derive_highway_width_fallback', function()
    it('uses two-way primary width when not oneway', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('primary', false)
      assert.are.equal(result.value, 18)
      assert.are.equal(result.source, 'highway_default')
    end)

    it('uses oneway primary width when is_oneway', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('primary', true)
      assert.are.equal(result.value, 12)
      assert.are.equal(result.source, 'highway_default_and_oneway')
    end)

    it('uses same width for residential regardless of oneway', function()
      local two_way = highway_width_fallbacks.derive_highway_width_fallback('residential', false)
      local oneway = highway_width_fallbacks.derive_highway_width_fallback('residential', true)
      assert.are.equal(two_way.value, 8)
      assert.are.equal(oneway.value, 8)
      assert.are.equal(oneway.source, 'highway_default')
    end)

    it('returns DEFAULT_FALLBACK for unknown highway', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('unknown', false)
      assert.are.equal(result.value, highway_width_fallbacks.DEFAULT_FALLBACK)
      assert.are.equal(result.source, 'highway_default')
    end)

    it('returns inferred motorway two-way width', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('motorway', false)
      assert.are.equal(result.value, 22)
    end)

    it('returns inferred motorway oneway width', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('motorway', true)
      assert.are.equal(result.value, 15)
      assert.are.equal(result.source, 'highway_default_and_oneway')
    end)

    it('returns inferred cycleway width', function()
      local result = highway_width_fallbacks.derive_highway_width_fallback('cycleway', false)
      assert.are.equal(result.value, 2)
    end)
  end)
end)
