describe('exit_processing_sealing', function()
  local exit_processing_sealing = require('topics.sealing.helper.exit_processing_sealing')

  it('keeps ordinary objects, also with access=private', function()
    assert.is_false(exit_processing_sealing({ highway = 'footway' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', access = 'private' }))
  end)

  it('skips bridge, tunnel and indoor unless `no`', function()
    assert.is_true(exit_processing_sealing({ highway = 'footway', bridge = 'yes' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', bridge = 'viaduct' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', bridge = 'no' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', tunnel = 'building_passage' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', tunnel = 'no' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', indoor = 'corridor' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', indoor = 'no' }))
  end)

  it('skips objects below ground or on roofs', function()
    assert.is_true(exit_processing_sealing({ highway = 'footway', location = 'underground' }))
    assert.is_true(exit_processing_sealing({ amenity = 'parking', location = 'rooftop' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', layer = '-1' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', level = '-1;0' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', layer = '1' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', level = '0' }))
  end)

  it('keeps landuse=construction with its construction=* subtag', function()
    assert.is_false(exit_processing_sealing({ landuse = 'construction', construction = 'residential' }))
  end)

  it('skips covered=yes only', function()
    assert.is_true(exit_processing_sealing({ highway = 'footway', covered = 'yes' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', covered = 'no' }))
  end)

  it('skips lifecycle objects', function()
    assert.is_true(exit_processing_sealing({ highway = 'footway', disused = 'yes' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', abandoned = 'yes' }))
    assert.is_true(exit_processing_sealing({ highway = 'footway', construction = 'yes' }))
    assert.is_true(exit_processing_sealing({ highway = 'construction', construction = 'footway' }))
    assert.is_true(exit_processing_sealing({ highway = 'proposed' }))
    assert.is_false(exit_processing_sealing({ highway = 'footway', disused = 'no' }))
  end)
end)
